/*
 * Транслитерация по одному символу, а не целыми словами: так предсказуемо
 * обрабатываются имена собственные, смешанные названия («Vegan-2») и любые
 * окончания без словаря.
 *
 * «ё» сводим к «e», а не к «yo»: в слаге это привычнее и короче
 * («ezhik», а не «yozhik»). Меняется одной строкой в таблице.
 */
const TRANSLIT: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'y',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'kh',
  ц: 'ts',
  ч: 'ch',
  ш: 'sh',
  щ: 'shch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
}

/*
 * Возвращает slug из русского названия: «Пломбир с клубникой» →
 * «plombir-s-klubnikoy». Всё, что не латиница и не цифра, становится
 * разделителем; повторы схлопываются, края обрезаются.
 *
 * Уникальность здесь не проверяется: за неё отвечает UNIQUE-индекс
 * products.slug, а Server Action превращает нарушение в ошибку поля.
 */
export const slugify = (value: string) => {
  const transliterated = Array.from(value.toLowerCase())
    .map((char) => TRANSLIT[char] ?? char)
    .join('')

  return transliterated
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}
